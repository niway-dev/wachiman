/**
 * Writing the workflow file safely (contract section 5.5). The mechanism is shared with
 * `wachiman pr-template` and lives in `../pr-template/write.ts`; this file keeps the names and the
 * behaviour `init` relies on: a backup of an existing file on every write, and messages that say
 * `init`.
 */
import { backupStamp, inspectManagedTarget, writeManagedFile, type TargetState, type WriteHooks } from "../pr-template/write";

export { backupStamp };
export type { TargetState, WriteHooks };

/** Looks at the target and its ancestors without following a link; refuses anything that is not a plain directory chain and a plain file. */
export const inspectTarget = (repoDir: string, relativePath: string): TargetState => inspectManagedTarget(repoDir, relativePath, "init");

/**
 * Writes `content` to the inspected target. An existing file is copied to `<target>.bak-<stamp>`
 * first (`-2`, `-3`… when that name is taken), and replaced only if it is the same file that was
 * inspected. A new file is linked into place, which fails if one appeared meanwhile. Returns the
 * backup path when one was made.
 */
export const writeWorkflow = (p: {
  repoDir: string;
  relativePath: string;
  content: string;
  inspected: TargetState;
  now: string;
  hooks?: WriteHooks;
}): { target: string; backup?: string } => writeManagedFile({ ...p, label: "init", backup: true });

/** The generated first line carries a version and a date; a re-run on another day still writes the same workflow. */
const withoutHeader = (text: string) => text.replace(/^# Generated by wachiman init [^\n]*\n/, "");

/** True when `existing` is what `rendered` would write, apart from the generated header line. */
export const sameWorkflow = (existing: string, rendered: string) => withoutHeader(existing) === withoutHeader(rendered);
