/**
 * `init` and `setup` through the real entry point, in a child process with a piped stdin (so no
 * terminal): the non-interactive contract. The interactive flows are tested on the run functions
 * with scripted prompts.
 */
import { afterAll, describe, expect, test } from "bun:test";
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { commit, emptyRepo, removeTempRepos } from "../test/support/temp-repo";
import { snapshotTree } from "../test/support/tree-snapshot";

const cli = join(import.meta.dir, "cli.ts");
const scratch: string[] = [];
afterAll(() => {
  scratch.forEach((d) => rmSync(d, { recursive: true, force: true }));
  removeTempRepos();
});

function machine() {
  const userHome = mkdtempSync(join(tmpdir(), "wachiman-wcli-user-"));
  scratch.push(userHome);
  const repo = emptyRepo();
  commit(repo, { "README.md": "hello\n" }, "init");
  const home = join(userHome, ".wachiman");
  const run = (args: string[], extra: Record<string, string> = {}) => {
    const out = Bun.spawnSync([process.execPath, cli, ...args], {
      env: { PATH: `${dirname(process.execPath)}:/usr/bin:/bin`, HOME: userHome, USER: "dev", WACHIMAN_HOME: home, ...extra },
      stdin: "ignore",
      cwd: repo,
    });
    return { code: out.exitCode, stdout: out.stdout.toString(), stderr: out.stderr.toString() };
  };
  return { repo, home, run };
}

const target = (repo: string) => join(repo, ".github", "workflows", "wachiman-review.yml");

describe("init through the CLI, without a terminal", () => {
  test("--mode github --operator me --dry-run without --version pins the bundled release", () => {
    const m = machine();
    const out = m.run(["init", "--mode", "github", "--operator", "me", "--dry-run"]);
    expect(out.code).toBe(0);
    expect(out.stdout).toContain("review.yml@v1.9.0\n");
  });

  test("--mode github --operator me --version v1.5.0 --dry-run prints the rendered file and writes nothing", () => {
    const m = machine();
    const before = snapshotTree(m.repo);
    const out = m.run(["init", "--mode", "github", "--operator", "me", "--version", "v1.5.0", "--dry-run"]);
    expect(out.code).toBe(0);
    expect(out.stdout).toMatch(/^# Generated by wachiman init \S+ on \d{4}-\d{2}-\d{2}; Actions is billed through the ANTHROPIC_API_KEY secret; local runs use your signed-in claude\.\nname: Wachiman review\n/);
    expect(out.stdout).toContain("      operator: me\n");
    expect(out.stdout).toContain("review.yml@v1.5.0\n");
    expect(snapshotTree(m.repo)).toEqual(before);
  });

  test("write, refuse a second run, then --force keeps a .bak copy", () => {
    const m = machine();
    const args = ["init", "--mode", "github", "--operator", "me", "--version", "v1.5.0"];
    expect(m.run(args).code).toBe(0);
    expect(readFileSync(target(m.repo), "utf8")).toContain("operator: me\n");
    const again = m.run(args);
    expect(again.code).toBe(2);
    expect(again.stderr).toContain("A workflow already exists at .github/workflows/wachiman-review.yml");
    expect(m.run([...args, "--force"]).code).toBe(0);
    const files = readdirSync(join(m.repo, ".github", "workflows"));
    expect(files.filter((f) => /^wachiman-review\.yml\.bak-\d{8}-\d{6}/.test(f))).toHaveLength(1);
  });

  test("--mode local writes nothing at all and prints the setup line", () => {
    const m = machine();
    const before = snapshotTree(m.repo);
    const out = m.run(["init", "--mode", "local"]);
    expect(out.code).toBe(0);
    expect(out.stderr).toContain("wachiman setup");
    expect(snapshotTree(m.repo)).toEqual(before);
    expect(existsSync(join(m.repo, ".github"))).toBe(false);
    expect(existsSync(m.home)).toBe(false);
  });

  test("without --mode, or --mode github without --operator, exits 2", () => {
    const m = machine();
    expect(m.run(["init"]).code).toBe(2);
    expect(m.run(["init", "--mode", "github", "--version", "v1.5.0"]).code).toBe(2);
    expect(m.run(["init", "--mode", "both", "--version", "v1.5.0"]).code).toBe(2);
  });

  test("--mode both writes the workflow and prints the setup line, without running setup", () => {
    const m = machine();
    const out = m.run(["init", "--mode", "both", "--operator", "me", "--version", "v1.5.0"]);
    expect(out.code).toBe(0);
    expect(existsSync(target(m.repo))).toBe(true);
    expect(out.stderr).toContain("wachiman setup");
    expect(existsSync(m.home)).toBe(false);
  });

  test("CI=true is not a terminal either, even if the streams were", () => {
    const m = machine();
    expect(m.run(["init"], { CI: "true" }).code).toBe(2);
  });

  test("an unknown flag and a stray argument are exit 2; init --help is exit 0 on stdout", () => {
    const m = machine();
    expect(m.run(["init", "--bogus"]).code).toBe(2);
    expect(m.run(["init", "stray"]).code).toBe(2);
    const help = m.run(["init", "--help"]);
    expect(help.code).toBe(0);
    expect(help.stdout).toContain("wachiman init [--mode github|local|both]");
  });
});

describe("setup through the CLI, without a terminal", () => {
  test("no --profile exits 2; --help exits 0", () => {
    const m = machine();
    expect(m.run(["setup"]).code).toBe(2);
    const help = m.run(["setup", "--help"]);
    expect(help.code).toBe(0);
    expect(help.stdout).toContain("wachiman setup [--profile <name>]");
  });
});
